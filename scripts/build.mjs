/** Build the plain-JavaScript Host modules and the native lazy Client factory. */
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, isAbsolute, join, relative } from 'node:path';
import { Script } from 'node:vm';
import { spawnSync } from 'node:child_process';
import { rollup } from 'rollup';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const src = join(root, 'src');
const output = join(root, 'lib');
const manifest = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));
const { createFinanceContract } = await import(pathToFileURL(join(src, 'contract.js')).href);
const { createFinanceClient } = await import(pathToFileURL(join(src, 'client-factory.js')).href);

async function filesIn(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const groups = await Promise.all(entries.map(async entry => {
    const path = join(directory, entry.name);
    return entry.isDirectory() ? filesIn(path) : [path];
  }));
  return groups.flat().sort();
}

await mkdir(output, { recursive: true });
const sourceFiles = (await filesIn(src)).filter(path => path.endsWith('.js'));
for (const path of sourceFiles) {
  const checked = spawnSync(process.execPath, ['--check', path], { stdio: 'inherit' });
  if (checked.status !== 0) throw new Error(`Source syntax check failed: ${relative(root, path)}`);
}
// One self-contained Host entry makes every implementation change visible to native module reconciliation.
const hostBundle = await rollup({
  input: join(src, 'host.js'),
  external: specifier => !specifier.startsWith('.') && !isAbsolute(specifier),
});
try {
  await hostBundle.write({ file: join(output, 'host.js'), format: 'es', sourcemap: false });
} finally {
  await hostBundle.close();
}

const client = `/* Financial Services native Client artifact. Generated by scripts/build.mjs. */\nwindow.__ModuleLoader__.load({\n  id: ${JSON.stringify(manifest.name)},\n  factory(require) {\n    const createFinanceContract = (${createFinanceContract.toString()});\n    const createFinanceClient = (${createFinanceClient.toString()});\n    return createFinanceClient(require('react'), require('zod').z, createFinanceContract);\n  }\n});\n`;
new Script(client, { filename: 'financial-services/lib/client.js' });
await writeFile(join(output, 'client.js'), client, 'utf8');
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
const sources = {};
for (const path of sourceFiles) sources[relative(root, path).replaceAll('\\', '/')] = sha256(await readFile(path));
const build = { package: manifest.name, version: manifest.version, format: 'dsh-native-lazy-factory',
  clientSha256: sha256(client), hostSha256: sha256(await readFile(join(output, 'host.js'))), sourceSha256: sources };
await writeFile(join(output, 'build-manifest.json'), JSON.stringify(build, null, 2) + '\n', 'utf8');
console.log(`Bundled ${sourceFiles.length - 1} Host/shared sources into one exported Host entry and one native Client factory for ${manifest.name}@${manifest.version}.`);
