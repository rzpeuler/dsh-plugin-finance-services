/** Build the plain-JavaScript Host modules and the native lazy Client factory. */
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, isAbsolute, join, relative } from 'node:path';
import { Script } from 'node:vm';
import { spawnSync } from 'node:child_process';
import { rollup } from 'rollup';

const flags = process.argv.slice(2);
if (flags.some(flag => flag !== '--client-only') || flags.length > 1) throw new Error('Supported option: --client-only (once)');
const clientOnly = flags.includes('--client-only');
const root = dirname(dirname(fileURLToPath(import.meta.url)));
const src = join(root, 'src');
const output = join(root, 'lib');
const manifest = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));
const { createFinanceContract } = await import(pathToFileURL(join(src, 'contract.js')).href);
const { createFinanceClient } = await import(pathToFileURL(join(src, 'client-factory.js')).href);

async function filesIn(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const groups = await Promise.all(entries.map(async entry => {
    const path = join(directory, entry.name);
    return entry.isDirectory() ? filesIn(path) : [path];
  }));
  return groups.flat().sort();
}

const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
let previous;
if (clientOnly) {
  previous = JSON.parse(await readFile(join(output, 'build-manifest.json'), 'utf8'));
  if (previous.package !== manifest.name || previous.version !== manifest.version) throw new Error('Client-only build requires the same existing package/version');
  const current = (await filesIn(src)).filter(path => path.endsWith('.js'));
  for (const path of current) {
    const key = relative(root, path).replaceAll('\\', '/');
    if (key !== 'src/client-factory.js' && sha256(await readFile(path)) !== previous.sourceSha256[key]) throw new Error(`Shared/Host source changed: full build required (${key})`);
  }
  for (const [entry, hash] of Object.entries(previous.entrySha256)) {
    if (sha256(await readFile(join(output, entry))) !== hash) throw new Error(`Existing ${entry} artifact mismatch`);
  }
  for (const [path, key] of [['assets/agent-manifest.json', 'assetsManifestSha256'], ['assets/source-snapshot.zip', 'sourceSnapshotSha256'], ['cordis.patch.yml', 'patchSha256']]) {
    if (sha256(await readFile(join(root, path))) !== previous[key]) throw new Error(`Non-Client artifact changed: ${path}`);
  }
} else {
  const archived = spawnSync(process.env.FINANCE_BUILD_PYTHON ?? 'python', [join(root, 'scripts/build-source-archive.py')], { stdio: 'inherit' });
  if (archived.status !== 0) throw new Error('Full-source ZIP build failed; set FINANCE_BUILD_PYTHON to a Python 3 executable.');
  await import('./generate-preset-patch.mjs');
}
await mkdir(output, { recursive: true });
const sourceFiles = (await filesIn(src)).filter(path => path.endsWith('.js'));
for (const path of sourceFiles) {
  const checked = spawnSync(process.execPath, ['--check', path], { stdio: 'inherit' });
  if (checked.status !== 0) throw new Error(`Source syntax check failed: ${relative(root, path)}`);
}
// Each actual plugin export contains all its own implementation; shared native libraries remain external.
for (const entry of clientOnly ? [] : ['host', 'role', 'floor', ...(manifest.exports['./data'] ? ['data'] : [])]) {
  const bundle = await rollup({
    input: join(src, `${entry}.js`),
    external: specifier => !specifier.startsWith('.') && !isAbsolute(specifier),
  });
  try {
    const file = join(output, entry === 'role' && manifest.exports['./role-numeric-1'] ? 'role-numeric-1.js' : `${entry}.js`);
    const generated = await bundle.generate({ format: 'es', sourcemap: false });
    const code = generated.output[0].code;
    let old;
    try { old = await readFile(file, 'utf8'); } catch (error) { if (error.code !== 'ENOENT') throw error; }
    // Preserve unchanged native Host/floor artifacts and the original retained role generation.
    if (old !== code) await writeFile(file, code, 'utf8');
    if (entry === 'role' && manifest.exports['./role-numeric-1']) {
      const legacy = join(output, 'role.js');
      try { await readFile(legacy); } catch (error) {
        if (error.code !== 'ENOENT') throw error;
        await writeFile(legacy, code, 'utf8');
      }
    }
  } finally {
    await bundle.close();
  }
}

const client = `/* Financial Services native Client artifact. Generated by scripts/build.mjs. */\nwindow.__ModuleLoader__.load({\n  id: ${JSON.stringify(manifest.name)},\n  factory(require) {\n    const createFinanceContract = (${createFinanceContract.toString()});\n    const createFinanceClient = (${createFinanceClient.toString()});\n    return createFinanceClient(require('react'), require('zod').z, createFinanceContract);\n  }\n});\n`;
new Script(client, { filename: 'financial-services/lib/client.js' });
let oldClient;
try { oldClient = await readFile(join(output, 'client.js'), 'utf8'); } catch (error) { if (error.code !== 'ENOENT') throw error; }
if (oldClient !== client) await writeFile(join(output, 'client.js'), client, 'utf8');
const sources = {};
for (const path of sourceFiles) sources[relative(root, path).replaceAll('\\', '/')] = sha256(await readFile(path));
const entrySha256 = {};
for (const entry of ['host', 'role', 'floor', ...(manifest.exports['./role-numeric-1'] ? ['role-numeric-1'] : []), ...(manifest.exports['./data'] ? ['data'] : [])]) entrySha256[`${entry}.js`] = sha256(await readFile(join(output, `${entry}.js`)));
const build = { package: manifest.name, version: manifest.version, format: 'dsh-native-lazy-factory',
  clientSha256: sha256(client), hostSha256: entrySha256['host.js'], entrySha256, sourceSha256: sources,
  assetsManifestSha256: sha256(await readFile(join(root, 'assets/agent-manifest.json'))),
  sourceSnapshotSha256: sha256(await readFile(join(root, 'assets/source-snapshot.zip'))),
  patchSha256: sha256(await readFile(join(root, 'cordis.patch.yml'))) };
try { await readFile(join(output, 'build-manifest.json')); } catch (error) { if (error.code !== 'ENOENT') throw error; }
await writeFile(join(output, 'build-manifest.json'), JSON.stringify(build, null, 2) + '\n', 'utf8');
console.log(clientOnly ? `Built Client only for ${manifest.name}@${manifest.version}; Host/role/floor/patch/source ZIP bytes were verified and not rewritten.` : `Built self-contained Host, role, floor${manifest.exports['./data'] ? ' and data' : ''} exports plus one native Client factory from ${sourceFiles.length} sources for ${manifest.name}@${manifest.version}.`);
